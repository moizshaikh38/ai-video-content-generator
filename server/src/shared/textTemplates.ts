/**
 * Creates a brand new track item from a given TextTemplate.
 */
export function createTrackItemFromTemplate(
  template: TextTemplate,
  trackId: string,
  currentTime: number,
  canvasDuration: number
): EditorTrackItem {
  const dur = template.defaultDuration || 3.0;
  const start = Math.max(0, Number(currentTime.toFixed(3)));
  const end = Math.min(canvasDuration, Number((start + dur).toFixed(3)));

  return {
    id: crypto.randomUUID(),
    track_id: trackId,
    type: 'TEXT',
    timeline_start: start,
    timeline_end: end > start ? end : start + 3.0,
    source_start: 0,
    source_end: dur,
    transform: { ...template.defaultTransform },
    speed: { speed: 1.0, pitch_preserved: true },
    text: { ...template.textConfig },
    effects: [],
    keyframes: [],
    locked: false,
    muted: true,
    hidden: false,
    z_index: 20,
  };
}

/**
 * Creates standard quick-add text layers (heading, subheading, body).
 */
export function createQuickAddTextItem(
  type: 'heading' | 'subheading' | 'body',
  trackId: string,
  currentTime: number,
  canvasDuration: number
): EditorTrackItem {
  const dur = 3.0;
  const start = Math.max(0, Number(currentTime.toFixed(3)));
  const end = Math.min(canvasDuration, Number((start + dur).toFixed(3)));

  const configs: Record<
    'heading' | 'subheading' | 'body',
    { text: string; fontSize: number; weight: 'bold' | 'medium' | 'normal'; anim: EditorTextAnimation; posY: number }
  > = {
    heading: { text: 'Add Heading', fontSize: 48, weight: 'bold', anim: 'pop', posY: -180 },
    subheading: { text: 'Add Subheading', fontSize: 32, weight: 'medium', anim: 'fade', posY: -80 },
    body: { text: 'Add body text here', fontSize: 26, weight: 'normal', anim: 'slide_up', posY: 180 },
  };

  const c = configs[type];

  return {
    id: crypto.randomUUID(),
    track_id: trackId,
    type: 'TEXT',
    timeline_start: start,
    timeline_end: end > start ? end : start + dur,
    source_start: 0,
    source_end: dur,
    transform: {
      position_x: 0,
      position_y: c.posY,
      scale: 1.0,
      rotation: 0,
      opacity: 1.0,
    },
    speed: { speed: 1.0, pitch_preserved: true },
    text: {
      text: c.text,
      font_family: 'Inter',
      font_size: c.fontSize,
      font_weight: c.weight,
      italic: false,
      alignment: 'center',
      color: '#FFFFFF',
      background_color: '#00000099',
      background_padding: 8,
      background_corner_radius: 6,
      preset: 'bold',
      animation: c.anim,
      animation_duration: 0.4,
    },
    effects: [],
    keyframes: [],
    locked: false,
    muted: true,
    hidden: false,
    z_index: 20,
  };
}
